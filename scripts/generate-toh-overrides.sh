#!/bin/sh
# Generate scripts/toh-id-overrides.tsv from static/toh/data.json.
#
# For each wiki entry, derive the buildbot profile id from the firmware URL
# filename:
#
#   …/openwrt-{version}-{target}-{subtarget}-{profile_id}-{rest}
#
# Emit one row per wiki entry where:
#   - the wiki suffix (deviceid after the brand prefix) disagrees with the
#     extracted buildbot profile id, AND
#   - the buildbot profile id appears in at least one active overview
#     (stable / oldstable release, or snapshots).
#
# Targets are filtered: x86 is generic and produces a handful of bogus
# extractions, so it is excluded.
#
# Usage:
#   scripts/generate-toh-overrides.sh [INPUT] [OUTPUT]
# Defaults: ./static/toh/data.json -> ./scripts/toh-id-overrides.tsv
#
# Network requirement: fetches .versions.json plus three overviews from
# downloads.openwrt.org. Run locally and commit the diff.

set -eu

IN="${1:-static/toh/data.json}"
OUT="${2:-scripts/toh-id-overrides.tsv}"

if ! command -v jq >/dev/null 2>&1; then
  printf 'generate-toh-overrides.sh: jq is required\n' >&2
  exit 1
fi

if ! command -v curl >/dev/null 2>&1; then
  printf 'generate-toh-overrides.sh: curl is required\n' >&2
  exit 1
fi

if [ ! -f "$IN" ]; then
  printf 'generate-toh-overrides.sh: input file not found: %s\n' "$IN" >&2
  exit 1
fi

mkdir -p "$(dirname "$OUT")"

TMPDIR=$(mktemp -d 2>/dev/null || mktemp -d -t toh)
trap 'rm -rf "$TMPDIR"' EXIT

UA='Mozilla/5.0 openwrt-website-build'

# 1. Fetch .versions.json → stable + oldstable.
curl -fsSL -A "$UA" \
  https://downloads.openwrt.org/.versions.json -o "$TMPDIR/versions.json"

STABLE=$(jq -r '.stable_version // empty' "$TMPDIR/versions.json")
OLDSTABLE=$(jq -r '.oldstable_version // empty' "$TMPDIR/versions.json")

# 2. Fetch overviews. Failures are non-fatal — skip the missing one.
fetch_overview() {
  url="$1"; out="$2"
  if curl -fsSL -A "$UA" "$url" -o "$out" 2>/dev/null; then
    printf '  [ok]   %s\n' "$url" >&2
  else
    rm -f "$out"
    printf '  [skip] %s (404 or unreachable)\n' "$url" >&2
  fi
}

printf 'generate-toh-overrides.sh: fetching active overviews…\n' >&2
[ -n "$STABLE" ]    && fetch_overview "https://downloads.openwrt.org/releases/$STABLE/.overview.json"    "$TMPDIR/o-stable.json"
[ -n "$OLDSTABLE" ] && fetch_overview "https://downloads.openwrt.org/releases/$OLDSTABLE/.overview.json" "$TMPDIR/o-oldstable.json"
fetch_overview "https://downloads.openwrt.org/snapshots/.overview.json" "$TMPDIR/o-snapshot.json"

# 3. Union of profile ids across all fetched overviews.
overview_files=$(find "$TMPDIR" -name 'o-*.json' -type f | tr '\n' ' ')
if [ -z "$overview_files" ]; then
  printf 'generate-toh-overrides.sh: no overviews fetched, aborting\n' >&2
  exit 1
fi
# shellcheck disable=SC2086
jq -s '[.[] | (.profiles // [])[] | .id] | unique' $overview_files \
  > "$TMPDIR/profile-ids.json"

count_valid=$(jq 'length' "$TMPDIR/profile-ids.json")
printf 'generate-toh-overrides.sh: %s buildbot profile ids in scope\n' "$count_valid" >&2

# 4. Walk toh.json, filter, emit overrides.
{
  printf '# wiki_suffix\tbuildbot_profile_id\n'
  printf '# Generated by scripts/generate-toh-overrides.sh from %s.\n' "$IN"
  printf '# `wiki_suffix` is the part of `deviceid` after the `<brand>:` prefix.\n'
  printf '# Each row is a wiki entry whose suffix disagrees with the buildbot\n'
  printf '# profile id baked into its firmware URL. The buildbot id must appear\n'
  printf '# in at least one of stable / oldstable release or snapshots overview.\n'
  printf '# x86 entries are excluded (target is generic).\n'
  printf '# scripts/split-toh.sh reads this file at runtime.\n'
  printf '#\n'

  jq -r --slurpfile valid "$TMPDIR/profile-ids.json" '
    def first_url:
      ([.firmwareopenwrtinstallurl,
        .firmwareopenwrtupgradeurl,
        .firmwareopenwrtsnapshotinstallurl,
        .firmwareopenwrtsnapshotupgradeurl]
       | map(. // []) | flatten
       | map(select(type == "string" and . != "" and . != "-")))
      | if length == 0 then null else .[0] end;

    def profile_from_url($t; $s):
      if (first_url == null) or ($t == "") or ($t == "-")
         or ($s == "") or ($s == "-") then null
      else
        first_url
        | sub("^.*/"; "")
        | sub("^openwrt-[0-9.]+(?:-rc[0-9]+)?-" + $t + "-" + $s + "-"; "")
        | sub("\\.[A-Za-z0-9]+(?:\\.[A-Za-z0-9]+)?$"; "")
        | sub("-(squashfs|ext4|jffs2|ubifs|ubi)(-[a-z0-9][a-z0-9-]*)?$"; "")
        | sub("-(factory|sysupgrade|kernel|rootfs|combined|initramfs|recovery|sdcard|tarball|boot|bootonly|preinit|installer)(-[a-z0-9][a-z0-9-]*)?$"; "")
        | if . == "" then null else . end
      end;

    ($valid[0] // []) as $valid_ids

    | .columns as $cols
    | .entries[]
    | . as $entry
    | ([range(0; $cols | length)]
        | map({key: $cols[.], value: $entry[.]})
        | from_entries) as $obj
    | $obj
    | (.target // "" | ascii_downcase) as $t
    | (.subtarget // "") as $s
    | (.deviceid // "") as $did
    | ($did | sub("^[^:]+:"; "")) as $wikisuf
    | (profile_from_url($t; $s)) as $bid
    | if $t == "x86" then empty
      elif ($bid != null) and ($wikisuf != $bid) and ($bid | IN($valid_ids[]))
        then [$wikisuf, $bid] | @tsv
      else empty
      end
  ' "$IN" | sort -u
} > "$OUT"

count=$(grep -cv '^#' "$OUT" 2>/dev/null || echo 0)
printf 'generate-toh-overrides.sh: %s overrides written to %s\n' "$count" "$OUT"
